#!/bin/sh
# Full-mode .env generator for LOCAL testing (README §Full mode).
#
# Usage: sh docker/gen-env.sh [path]     # default: .env (refuses to overwrite)
#
# Defaults: vendored Jitsi stack (stable-11248-2) on https://localhost:8443
# (self-signed cert — open it once in the browser to accept it), JitsiMap app
# on http://localhost:8080. For a real domain pass overrides in:
#   JITSI_DOMAIN=meet.example.org PUBLIC_URL=https://meet.example.org sh docker/gen-env.sh
set -eu

target="${1:-.env}"
[ -e "$target" ] && { echo "refusing to overwrite $target — remove it first" >&2; exit 1; }
command -v openssl >/dev/null 2>&1 || { echo "openssl is required" >&2; exit 1; }
rand() { openssl rand -hex 16; }

domain="${JITSI_DOMAIN:-localhost}"
port="${HTTPS_PORT:-8443}"
base="${PUBLIC_URL:-https://${domain}:${port}}"
cfg="${CONFIG:-$PWD/.jitsi-meet-cfg}"

cat > "$target" <<EOF
# Generated by docker/gen-env.sh — full-mode quickstart (README §Full mode).
# Vendored upstream stack: docker-compose.jitsi.yml (stable-11248-2, profile "full").

# --- JitsiMap app (rendered into /config.json at container start, §12.3) ---
JITSI_DOMAIN=${domain}
# The vendored stack's INTERNAL XMPP domains (upstream defaults) — the client
# addresses these over the websocket; they are not the public host.
JITSI_XMPP_DOMAIN=meet.jitsi
JITSI_MUC_DOMAIN=muc.meet.jitsi
JITSI_WEBSOCKET_URL=wss://${domain}:${port}/xmpp-websocket
JITSI_BOSH_URL=https://${domain}:${port}/http-bind
JITSI_AUTH_MODE=anonymous
DEFAULT_MAP=office
APP_PORT=8080

# --- Vendored Jitsi stack (upstream env surface, stable-11248-2) ---
CONFIG=${cfg}
HTTP_PORT=8000
HTTPS_PORT=${port}
TZ=UTC
PUBLIC_URL=${base}

# Generated service secrets (never reuse, never commit this file).
XMPP_AUTH_PASS=$(rand)
XMPP_GUEST_PASS=$(rand)
XMPP_MUC_PASS=$(rand)
XMPP_INTERNAL_MUC_PASS=$(rand)
JICOFO_AUTH_PASSWORD=$(rand)
JVB_AUTH_PASSWORD=$(rand)
JIGASI_XMPP_PASSWORD=$(rand)
JIGASI_TRANSCRIBER_PASSWORD=$(rand)
JIBRI_RECORDER_PASSWORD=$(rand)
JIBRI_XMPP_PASSWORD=$(rand)
EOF

# The stack bind-mounts this tree; create it up front (upstream handbook step).
for d in jicofo jicofo/custom-ca jvb jvb/custom-ca \
         prosody/config prosody/custom-ca prosody/prosody-plugins-custom \
         storage/prosody storage/transcripts storage/web \
         tmp/web-load-test web web/custom-ca; do
  mkdir -p "$cfg/$d"
done

echo "wrote $target  (JITSI_DOMAIN=${domain}, PUBLIC_URL=${base}, CONFIG=${cfg})"
echo "next: docker compose -f docker-compose.yml -f docker-compose.jitsi.yml --profile full up -d --build"
